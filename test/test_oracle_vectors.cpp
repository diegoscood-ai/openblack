TEST(OracleVectors, GameRandIsTheOriginals)
{
	for (const auto& c : k_GameRandCases)
	{
		// the game's GameRand gives 0 for 0 with no draw
		uint32_t seed = c.seed;
		const uint32_t r = c.max == 0 ? 0u : game_random::SeededRandom(c.max, seed);
		EXPECT_EQ(r, c.ret);
		EXPECT_EQ(seed, c.seed_after);
	}
}

TEST(OracleVectors, GameFloatRandIsTheOriginals)
{
	for (const auto& c : k_GameFloatRandCases)
	{
		uint32_t seed = c.seed;
		const float r = game_random::FloatRand(std::bit_cast<float>(c.scale), seed);
		EXPECT_EQ(std::bit_cast<uint32_t>(r), c.ret_f32);
		EXPECT_EQ(seed, c.seed_after);
	}
}

TEST(OracleVectors, TheAngleBetweenTwoPointsIsTheOriginals)
{
	for (const auto& c : k_GetAngleFromXZCases)
	{
		const map_coords::MapCoords from {static_cast<int32_t>(c.from_x), static_cast<int32_t>(c.from_z), 0.0f};
		const map_coords::MapCoords to {static_cast<int32_t>(c.to_x), static_cast<int32_t>(c.to_z), 0.0f};
		EXPECT_EQ(gutils::GetAngleFromXZ(from, to), c.ret);
	}
}

TEST(OracleVectors, TheMatricesProductAndInverseAreTheOriginals)
{
	for (const auto& c : k_MulCases)
	{
		ExpectBits(affine::Mul(Matrix(c.a), Matrix(c.b)), c.a_after);
	}
	for (const auto& c : k_SetInverseCases)
	{
		ExpectBits(affine::Inverse(Matrix(c.m)), c.inv);
	}
}

TEST(OracleVectors, TheCircleOfTheDancesIsTheOriginals)
{
	const auto circle = ecs::dance_shapes::Build(0);
	const auto& points = k_MakeShapeCircleCases.front().points;
	for (size_t k = 0; k < circle.size(); ++k)
	{
		EXPECT_EQ(static_cast<uint32_t>(circle[k].x), points[2 * k]) << "point " << k;
		EXPECT_EQ(static_cast<uint32_t>(circle[k].y), points[2 * k + 1]) << "point " << k;
	}
}
