TEST(LandLightTable, FlashZeroLeavesTheTable)
{
	LandLightTable a;
	LandLightTable b;
	ASSERT_TRUE(a.Load(Palette()));
	ASSERT_TRUE(b.Load(Palette()));
	a.Build(1.0f, 0.2f, 0.3f);
	b.Build(1.0f, 0.2f, 0.3f, 0);
	for (size_t i = 0; i < LandLightTable::k_Size; ++i)
	{
		EXPECT_EQ(a.GetRaw(i), b.GetRaw(i));
	}
}

