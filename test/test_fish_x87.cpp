TEST(FishShoalBits, AFishsSwimStepGivesTheOriginalsBits)
{
	for (const auto& c : k_FishStepCases)
	{
		Fish fish {};
		fish.position = {F(c.x), 0.0f, F(c.z)};
		fish.heading = F(c.heading);
		fish.speed = F(c.speed);
		fish.turnRate = F(c.rate);
		fish.fleeTime = F(c.fright);
		// the frame's time as the original takes it from its milliseconds
		const float seconds = static_cast<float>(c.ms) * 0.001f;
		ecs::StepFish(fish, {F(c.targetX), 0.0f, F(c.targetZ)}, seconds);
		EXPECT_EQ(Bits(fish.position.x), c.outX) << std::hex << c.heading;
		EXPECT_EQ(Bits(fish.position.z), c.outZ) << std::hex << c.heading;
		EXPECT_EQ(Bits(fish.heading), c.outHeading) << std::hex << c.heading;
	}
}

TEST(FishShoalBits, AShoalsScareGivesTheOriginalsTargetAndHeading)
{
	for (const auto& c : k_ShoalScareCases)
	{
		FishShoal shoal {};
		shoal.centre = {F(c.centre[0]), F(c.centre[1]), F(c.centre[2])};
		shoal.fish.at(0).position = {F(c.fish[0]), F(c.fish[1]), F(c.fish[2])};
		shoal.fish.at(0).heading = F(c.heading);
		// the game's CRT random float from the C library's draw
		const auto random = [draw = c.draw](float low, float high) {
			const float r = static_cast<float>(draw) * F(0x38000100u);
			return r * (high - low) + low;
		};
		ecs::ScareShoal(shoal, 1, {F(c.point[0]), F(c.point[1]), F(c.point[2])}, random);
		EXPECT_EQ(Bits(shoal.target.x), c.outTarget[0]) << c.draw;
		EXPECT_EQ(Bits(shoal.target.y), c.outTarget[1]) << c.draw;
		EXPECT_EQ(Bits(shoal.target.z), c.outTarget[2]) << c.draw;
		EXPECT_EQ(Bits(shoal.fish.at(0).heading), c.outHeading) << c.draw;
	}
}

TEST(FishPuzzleBits, TheNetsRingGivesTheOriginalsBits)
{
	for (const auto& c : k_NetRingCases)
	{
		FishPlot net {};
		net.centre = {F(c.centre[0]), F(c.centre[1]), F(c.centre[2])};
		net.closure = F(c.size);
		net.phase = F(c.phase);
		net.closing = true;
		ecs::AdvanceFishPlot(net, static_cast<float>(c.ms) * 0.001f);
		EXPECT_EQ(Bits(net.closure), c.outSize);
		EXPECT_EQ(Bits(net.phase), c.outPhase);
		for (size_t i = 0; i < FishPlot::k_Floats; ++i)
		{
			EXPECT_EQ(Bits(net.points[i].x), c.points[3 * i]) << "point " << i;
			EXPECT_EQ(Bits(net.points[i].y), c.points[3 * i + 1]) << "point " << i;
			EXPECT_EQ(Bits(net.points[i].z), c.points[3 * i + 2]) << "point " << i;
			EXPECT_EQ(Bits(ecs::FishPlotWobble(net, i)), c.wobbles[i]) << "wobble " << i;
		}
	}
}
