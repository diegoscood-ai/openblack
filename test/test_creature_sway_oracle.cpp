TEST(CreatureSwayOracle, AKickMatchesTheOriginalBitForBit)
{
	for (size_t row = 0; row < k_Kicks.size(); ++row)
	{
		const auto& c = k_Kicks[row];
		Sway sway;
		sway.lowerVelocity = ToVec(c.lowerBefore);
		sway.upperVelocity = ToVec(c.upperBefore);
		sway.frameSeconds = std::bit_cast<float>(c.frameSeconds);
		const float heightAboveLand = std::bit_cast<float>(c.pointHeight) - std::bit_cast<float>(c.ground);
		const float splitHeight = k_UpperHeightPerSize * std::bit_cast<float>(c.size);
		Kick(sway, ToVec(c.force), heightAboveLand, splitHeight, std::bit_cast<float>(c.mass));
		ExpectBits(sway.lowerVelocity, c.lowerAfter, row, "lower");
		ExpectBits(sway.upperVelocity, c.upperAfter, row, "upper");
		EXPECT_TRUE(sway.active) << "row " << row;
	}
}

TEST(CreatureSwayOracle, ATurnOfTheSpringMatchesTheOriginalBitForBit)
{
	for (size_t row = 0; row < k_Steps.size(); ++row)
	{
		const auto& c = k_Steps[row];
		Sway sway;
		sway.lowerVelocity = ToVec(c.lowerVelocity);
		sway.upperVelocity = ToVec(c.upperVelocity);
		sway.lowerOffset = ToVec(c.lowerOffset);
		sway.upperOffset = ToVec(c.upperOffset);
		sway.drive = ToVec(c.drive);
		sway.active = true;
		Step(sway, ToVec(c.push), std::bit_cast<float>(c.seconds), std::bit_cast<float>(c.mass));
		ExpectBits(sway.lowerVelocity, c.lowerVelocityAfter, row, "lower speed");
		ExpectBits(sway.upperVelocity, c.upperVelocityAfter, row, "upper speed");
		ExpectBits(sway.lowerOffset, c.lowerOffsetAfter, row, "lower offset");
		ExpectBits(sway.upperOffset, c.upperOffsetAfter, row, "upper offset");
		ExpectBits(sway.drive, c.driveAfter, row, "drive");
		EXPECT_EQ(sway.active, c.activeAfter) << "row " << row;
	}
}
