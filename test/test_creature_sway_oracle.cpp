glm::vec3 ToVec(const std::array<uint32_t, 3>& bits)
{
	return {std::bit_cast<float>(bits[0]), std::bit_cast<float>(bits[1]), std::bit_cast<float>(bits[2])};
}

void ExpectBits(const glm::vec3& got, const std::array<uint32_t, 3>& expected, size_t row, const char* what)
{
	for (int i = 0; i < 3; ++i)
	{
		EXPECT_EQ(std::bit_cast<uint32_t>(got[i]), expected[i]) << "row " << row << ' ' << what << " axis " << i;
	}
}
