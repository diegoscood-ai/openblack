affine::AffineMatrix Matrix(const std::array<uint32_t, 12>& bits)
{
	affine::AffineMatrix m;
	for (size_t i = 0; i < m.m.size(); ++i)
	{
		m.m[i] = std::bit_cast<float>(bits[i]);
	}
	return m;
}

void ExpectBits(const affine::AffineMatrix& m, const std::array<uint32_t, 12>& bits)
{
	for (size_t i = 0; i < m.m.size(); ++i)
	{
		EXPECT_EQ(std::bit_cast<uint32_t>(m.m[i]), bits[i]) << "cell " << i;
	}
}
